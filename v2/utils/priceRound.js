// تقريب أسعار الليرة بقائمة الأسعار، بخطوة على قد السعر:
// تقريب لأقرب 100 دايماً كان ياكل الربح بالأسعار الصغيرة (مثلاً سعر بالليرة الجديدة):
// 90 + 12.5% = 101 ← كانت تصير 200 (ربح 122%)، هلق بتصير 105
//   أقل من 100   ← لأقرب 1
//   100 – 999    ← لأقرب 5
//   1,000 وفوق   ← لأقرب 100 (متل قبل)
export const sypStep = (n) => (n < 100 ? 1 : n < 1000 ? 5 : 100);

// الكسور الصغيرة من الضرب (101.00000001) ما لازم تطلّع خطوة كاملة لفوق
const EPS = 1e-9;

// لأقرب خطوة (سعر الجملة)
export const roundSyp = (n) => {
  const step = sypStep(n);
  return Math.round(n / step) * step;
};

// لفوق (سعر المبيع: ما منبيع تحت نسبة الربح)
export const ceilSyp = (n) => {
  const step = sypStep(n);
  return Math.ceil(n / step - EPS) * step;
};
